static Util::Config::Node s_runtime_config("Global");
static SDL_Window *s_window = nullptr;
static int aaValue = 1;
static unsigned duplicateErrors = 0;
static Result ErrorLog(const char *format, ...)
{
  char text[2048];
  va_list args;
  va_start(args, format);
  vsnprintf(text, sizeof(text), format, args);
  va_end(args);
  if (std::string(text).find("CreateGLScreen() called more than once") != std::string::npos)
    ++duplicateErrors;
  else
    fprintf(stderr, "%s\n", text);
  return Result::FAIL;
}

// Generated by the runner directly from the current production Main.cpp.
#include "DisplayFunctions.inc"

int main()
{
  SDL_SetMainReady();
  s_runtime_config.Set("New3DEngine", true);
  s_runtime_config.Set("VSync", false);
  s_runtime_config.Set("WideScreen", false);
  DestroyGLScreen(); // Cleanup before any window exists must be harmless.
  for (unsigned session = 0; session < 10; ++session)
  {
    // Mirror the launcher using its own local window/context, then shutting SDL
    // down before the emulator creates a different window in the same process.
    assert(SDL_Init(SDL_INIT_VIDEO) == 0);
    SDL_GL_SetAttribute(SDL_GL_CONTEXT_MAJOR_VERSION, 4);
    SDL_GL_SetAttribute(SDL_GL_CONTEXT_MINOR_VERSION, 1);
    SDL_GL_SetAttribute(SDL_GL_CONTEXT_PROFILE_MASK, SDL_GL_CONTEXT_PROFILE_CORE);
    SDL_Window *launcher = SDL_CreateWindow("Launcher lifecycle test", 0, 0, 64, 64, SDL_WINDOW_OPENGL | SDL_WINDOW_HIDDEN);
    assert(launcher);
    SDL_GLContext launcherContext = SDL_GL_CreateContext(launcher);
    assert(launcherContext);
    SDL_GL_DeleteContext(launcherContext);
    SDL_DestroyWindow(launcher);
    SDL_Quit();

    unsigned x = 0, y = 0, width = 496, height = 384, totalWidth = 0, totalHeight = 0;
    const auto create = [&]() {
      return CreateGLScreen(true, "Game lifecycle test", false,
                            &x, &y, &width, &height, &totalWidth, &totalHeight, false, false);
    };
    assert(create() == Result::OKAY);
    SDL_Window *liveWindow = s_window;
    assert(liveWindow);
    // Keep the duplicate-live-window guard: do not hide bugs by removing it.
    assert(create() == Result::FAIL);
    assert(s_window == liveWindow);
    DestroyGLScreen();
    if (s_window != nullptr)
    {
      fprintf(stderr, "FAIL: destroyed window still stored in s_window; the next game launch will hit the duplicate-window guard.\n");
      return 1;
    }
    DestroyGLScreen(); // Must not delete the old window/context a second time.
    SDL_Quit();
  }
  assert(duplicateErrors == 10);
  puts("PASS 10 launcher/game/restart cycles, cleared window handle, idempotent cleanup, and live-window duplicate guard");
}
